"""Pins `MainWindow.reset_dock_layout` to the procedural layout, for tests of dock mechanics.

The bundled default layouts in `src.ui.window.default_layouts` are hand-arranged and regenerated by saving a layout, so
tests that move docks around start from `MainWindow._reset_dock_layout_procedural` instead: Tools, Image generation
and ControlNet tabified above Layers, Color and Navigation, in the right area (the bottom area on a portrait screen).
`test/ui/window/default_layouts_test.py` covers the bundled layouts.
"""
from contextlib import AbstractContextManager
from unittest import TestCase
from unittest.mock import patch

from src.ui.window.main_window import MainWindow


def procedural_layout() -> AbstractContextManager:
    """Returns a patch that makes `MainWindow.reset_dock_layout`, and so a new window's first layout, procedural."""
    # pylint: disable-next=protected-access
    return patch.object(MainWindow, 'reset_dock_layout', MainWindow._reset_dock_layout_procedural)


def use_procedural_layout(test: TestCase) -> None:
    """Applies `procedural_layout` until the test ends. Call it before creating a MainWindow."""
    layout_patch = procedural_layout()
    layout_patch.start()
    test.addCleanup(layout_patch.stop)

"""Generates `src/config/generated_keys.py`, the config key constants, from the definition files in `resources/config/`.

Each config class inherits one generated class of `NAME: Final = 'name'` constants, one per key in its definition file,
so `Cache.PROMPT` exists at import time and carries a type. Run this after adding, renaming or removing a definition.
`test/config/generated_keys_test.py` fails while the committed module is out of date.

Usage:
    python scripts/generate_config_keys.py           # rewrite the module
    python scripts/generate_config_keys.py --check   # exit 1 if the module is out of date
"""
import argparse
import json
import os
import sys

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFINITION_DIR = os.path.join(PROJECT_DIR, 'resources', 'config')
OUTPUT_PATH = os.path.join(PROJECT_DIR, 'src', 'config', 'generated_keys.py')

# Definition file name -> generated class name. The config class that loads the file inherits the generated class.
KEY_CLASSES = {
    'application_config_definitions.json': 'AppConfigKeys',
    'cache_value_definitions.json': 'CacheKeys',
    'key_config_definitions.json': 'KeyConfigKeys',
    'a1111_setting_definitions.json': 'A1111ConfigKeys',
}

HEADER = '''"""Config key constants, generated from `resources/config/*_definitions.json`.

Generated by `python scripts/generate_config_keys.py`. Don't edit this file by hand.
"""
from typing import Final
'''


def render() -> str:
    """Returns the generated module's source text."""
    sections = [HEADER]
    for file_name, class_name in KEY_CLASSES.items():
        with open(os.path.join(DEFINITION_DIR, file_name), encoding='utf-8') as file:
            keys = sorted(json.load(file))
        lines = [f'\n\nclass {class_name}:',
                 f'    """Key constants for the definitions in `resources/config/{file_name}`."""',
                 '']
        lines += [f'    {key.upper()}: Final = {key!r}' for key in keys]
        sections.append('\n'.join(lines) + '\n')
    return ''.join(sections)


def main() -> int:
    """Writes the generated module, or with `--check` reports whether it is current."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='exit 1 if the generated module is out of date')
    args = parser.parse_args()
    expected = render()
    current = None
    if os.path.isfile(OUTPUT_PATH):
        with open(OUTPUT_PATH, encoding='utf-8') as file:
            current = file.read()
    if args.check:
        if current != expected:
            output_name = os.path.relpath(OUTPUT_PATH, PROJECT_DIR)
            print(f'{output_name} is out of date: run python scripts/generate_config_keys.py', file=sys.stderr)
            return 1
        return 0
    if current != expected:
        with open(OUTPUT_PATH, 'w', encoding='utf-8', newline='\n') as file:
            file.write(expected)
    return 0


if __name__ == '__main__':
    sys.exit(main())

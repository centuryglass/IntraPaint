"""Generates `doc/file_map.md`, a one-line description of every source file, from module and package docstrings.

A file's description is its summary line: the first line of its module docstring, or of its leading comment block in a
shell script. That line must stand alone (a blank line or the end of the docstring follows it), end with a period, and
fit on the docstring's opening line, which is at most `MAX_SUMMARY_LENGTH` characters after the quotes. A package's
summary comes from its `__init__.py` and heads its section of the map. Files with no docstring to read, such as the
config definition files, keep the description they have in the committed map, so edit those in `doc/file_map.md`
directly.

The map lists `src/` (except the legacy `src/glid_3_xl/`), `scripts/`, `resources/config/` and the entry points.

The script also writes `doc/file_map.html` (gitignored), the same map with collapsible packages and, for each module,
its full docstring, line count, top-level classes and the files that import it.

Usage:
    python scripts/file_map.py           # rewrite doc/file_map.md and doc/file_map.html, and list summary problems
    python scripts/file_map.py --check   # exit 1 if any summary has a problem or doc/file_map.md is out of date
"""
import argparse
import ast
import html
import os
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass, field
from typing import Optional

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP_PATH = os.path.join('doc', 'file_map.md')
HTML_PATH = os.path.join('doc', 'file_map.html')

# A docstring's opening line holds four leading spaces' worth of quotes and indentation at most, within 120 columns.
MAX_SUMMARY_LENGTH = 117
MARKDOWN_LINE_LENGTH = 120

ROOT_FILES = ('IntraPaint.py', 'IntraPaint_server.py', 'setup.py', 'IntraPaint.spec')
EXCLUDED_DIRS = ('src/glid_3_xl/',)

# Directories that are not Python packages, so they have no `__init__.py` to describe them.
DIRECTORY_SUMMARIES = {
    '': 'Entry points and build configuration.',
    'scripts': 'Developer tools: builds, CI checks, code generation and UI captures. None of them ship with the app.',
    'resources/config': 'Config option definitions, the source of truth for every option (AGENTS.md, "Config system").',
}

MAP_HEADER = '''# File map

One line for every source file, generated by `python scripts/file_map.py` from each module's docstring summary line.
Edit a module's docstring rather than this file, except for files with no docstring (the config definitions, shell
scripts without a header comment and `IntraPaint.spec`), whose descriptions this file holds. The script's docstring
describes the summary format, and it also writes a browsable `doc/file_map.html` with more detail.
'''

PROJECT_ROOT = ''

MAP_ENTRY = re.compile(r'^- `(?P<path>[^`]+)`: (?P<text>.*)$')


@dataclass
class SourceFile:
    """A file listed in the map, with what the map and the HTML page show about it."""
    path: str
    summary: Optional[str] = None
    docstring: Optional[str] = None
    problem: Optional[str] = None
    line_count: int = 0
    classes: list[str] = field(default_factory=list)
    importers: list[str] = field(default_factory=list)

    @property
    def directory(self) -> str:
        """The directory the file is listed under, '' for the project root."""
        return os.path.dirname(self.path)


def tracked_files() -> list[str]:
    """Returns every file git tracks, as paths relative to the project root."""
    listing = subprocess.run(['git', 'ls-files'], cwd=PROJECT_DIR, capture_output=True, text=True, check=True)
    return listing.stdout.splitlines()


def is_listed(path: str) -> bool:
    """Returns whether the map lists a tracked file."""
    if path.startswith(EXCLUDED_DIRS):
        return False
    if path.startswith('src/'):
        return path.endswith('.py')
    if path.startswith('scripts/'):
        return path.endswith(('.py', '.sh')) and path.count('/') == 1
    if path.startswith('resources/config/'):
        return path.endswith('.json')
    return path in ROOT_FILES


def read_python_docstring(source: str) -> Optional[str]:
    """Returns a Python module's docstring, or None if it has none or doesn't parse."""
    try:
        return ast.get_docstring(ast.parse(source))
    except SyntaxError:
        return None


def read_shell_header(source: str) -> Optional[str]:
    """Returns the comment block at the top of a shell script, after the shebang, without its comment markers."""
    lines = []
    for line in source.splitlines():
        if line.startswith('#!') and not lines:
            continue
        if not line.startswith('#'):
            break
        lines.append(line[1:].strip())
    return '\n'.join(lines).strip() or None


def summary_problem(docstring: Optional[str]) -> Optional[str]:
    """Returns what makes a docstring's first line unusable as a summary line, or None if it is usable."""
    if not docstring:
        return 'no docstring'
    lines = docstring.splitlines()
    if len(lines) > 1 and lines[1].strip():
        return 'summary continues onto a second line'
    if len(lines[0]) > MAX_SUMMARY_LENGTH:
        return f'summary is {len(lines[0])} characters, over {MAX_SUMMARY_LENGTH}'
    if not lines[0].endswith('.'):
        return 'summary does not end with a period'
    return None


def module_name(path: str) -> str:
    """Returns the dotted import name of a Python file under the project root."""
    name = path[:-len('.py')].replace('/', '.')
    return name[:-len('.__init__')] if name.endswith('.__init__') else name


def imported_modules(tree: ast.AST, known: set[str]) -> set[str]:
    """Returns the names in `known` that a parsed module imports, from any scope."""
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(alias.name for alias in node.names if alias.name in known)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            for alias in node.names:
                submodule = f'{node.module}.{alias.name}'
                if submodule in known:
                    found.add(submodule)
                elif node.module in known:
                    found.add(node.module)
    return found


def load_carried_descriptions() -> dict[str, str]:
    """Returns the descriptions in the committed map, by path, with wrapped lines joined."""
    descriptions: dict[str, str] = {}
    map_file = os.path.join(PROJECT_DIR, MAP_PATH)
    if not os.path.exists(map_file):
        return descriptions
    last_path = None
    with open(map_file, encoding='utf-8') as file:
        for line in file:
            line = line.rstrip('\n')
            match = MAP_ENTRY.match(line)
            if match:
                last_path = match.group('path')
                descriptions[last_path] = match.group('text')
            elif last_path is not None and line.startswith('  '):
                descriptions[last_path] += ' ' + line.strip()
            else:
                last_path = None
    return descriptions


def collect(paths: list[str]) -> list[SourceFile]:
    """Reads every listed file's summary, size, classes and importers."""
    carried = load_carried_descriptions()
    files = [SourceFile(path) for path in sorted(paths, key=sort_key) if is_listed(path)]
    trees: dict[str, ast.AST] = {}
    for source_file in files:
        with open(os.path.join(PROJECT_DIR, source_file.path), encoding='utf-8') as file:
            source = file.read()
        source_file.line_count = len(source.splitlines())
        if source_file.path.endswith('.py'):
            source_file.docstring = read_python_docstring(source)
            source_file.problem = summary_problem(source_file.docstring)
            try:
                tree = ast.parse(source)
            except SyntaxError:
                continue
            trees[source_file.path] = tree
            source_file.classes = [node.name for node in tree.body if isinstance(node, ast.ClassDef)]
        elif source_file.path.endswith('.sh'):
            source_file.docstring = read_shell_header(source)
            source_file.problem = summary_problem(source_file.docstring)
        if source_file.docstring and not source_file.problem:
            source_file.summary = source_file.docstring.splitlines()[0]
        elif not source_file.path.endswith(('.py', '.sh')):
            source_file.summary = carried.get(source_file.path)
            if source_file.summary is None:
                source_file.problem = 'no description: add one to doc/file_map.md'

    by_module = {module_name(f.path): f for f in files if f.path.startswith('src/') and f.path.endswith('.py')}
    known_modules = set(by_module)
    importer_paths = [path for path in paths if path.endswith('.py') and not path.startswith(EXCLUDED_DIRS)]
    for path in importer_paths:
        tree = trees.get(path)
        if tree is None:
            try:
                with open(os.path.join(PROJECT_DIR, path), encoding='utf-8') as file:
                    tree = ast.parse(file.read())
            except (SyntaxError, UnicodeDecodeError, FileNotFoundError):
                continue
        for name in imported_modules(tree, known_modules):
            if by_module[name].path != path:
                by_module[name].importers.append(path)
    for source_file in files:
        source_file.importers.sort()
    return files


def sort_key(path: str) -> tuple[str, int, str]:
    """Sorts files by directory, with each package's `__init__.py` first."""
    directory, name = os.path.split(path)
    return directory, 0 if name == '__init__.py' else 1, name


def directory_summary(directory: str, by_path: dict[str, SourceFile]) -> Optional[str]:
    """Returns the summary that heads a directory's section, from its `__init__.py` or `DIRECTORY_SUMMARIES`."""
    package = by_path.get(f'{directory}/__init__.py')
    if package is not None:
        return package.summary
    return DIRECTORY_SUMMARIES.get(directory)


def sections(files: list[SourceFile]) -> list[tuple[str, list[SourceFile]]]:
    """Groups files by directory, with the project root first."""
    grouped: dict[str, list[SourceFile]] = {}
    for source_file in files:
        grouped.setdefault(source_file.directory, []).append(source_file)
    return sorted(grouped.items(), key=lambda item: (item[0] != '', item[0]))


def wrap(text: str, first_prefix: str, rest_prefix: str) -> list[str]:
    """Wraps text to the Markdown line length."""
    return textwrap.wrap(text, MARKDOWN_LINE_LENGTH, initial_indent=first_prefix, subsequent_indent=rest_prefix,
                         break_long_words=False, break_on_hyphens=False)


def render_markdown(files: list[SourceFile]) -> str:
    """Returns the content of `doc/file_map.md`."""
    by_path = {f.path: f for f in files}
    lines = [MAP_HEADER]
    for directory, members in sections(files):
        lines.append(f'## `{directory}`' if directory else '## Project root')
        lines.append('')
        summary = directory_summary(directory, by_path)
        if summary:
            lines.extend(wrap(summary, '', ''))
            lines.append('')
        for source_file in members:
            if source_file.path.endswith('/__init__.py'):
                continue
            entry = f'`{source_file.path}`: {source_file.summary}' if source_file.summary else f'`{source_file.path}`:'
            lines.extend(wrap(entry, '- ', '  '))
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'



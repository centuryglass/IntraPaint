def inline_html(text: str) -> str:
    """Escapes text for HTML, rendering its backtick spans as code."""
    return re.sub(r'`([^`]+)`', r'<code>\1</code>', html.escape(text))


def render_file_html(source_file: SourceFile) -> str:
    """Returns one file's collapsible entry in the HTML page."""
    name = os.path.basename(source_file.path)
    summary = inline_html(source_file.summary or '')
    search = html.escape(' '.join((source_file.path, source_file.summary or '')).lower())
    parts = [f'<details class="file" data-search="{search}"><summary><code>{html.escape(name)}</code> {summary}'
             '</summary><div class="body">',
             f'<div class="meta">{html.escape(source_file.path)}: {source_file.line_count} lines</div>']
    if source_file.docstring and source_file.docstring != source_file.summary:
        parts.append(f'<pre>{html.escape(source_file.docstring)}</pre>')
    if source_file.classes:
        parts.append('<div>Classes: ' + ', '.join(f'<code>{html.escape(c)}</code>' for c in source_file.classes)
                     + '</div>')
    if source_file.path.startswith('src/'):
        if source_file.importers:
            items = ''.join(f'<li><code>{html.escape(p)}</code></li>' for p in source_file.importers)
            parts.append(f'<div>Imported by {len(source_file.importers)}:</div><ul>{items}</ul>')
        else:
            parts.append('<div class="empty">Imported by nothing.</div>')
    parts.append('</div></details>')
    return ''.join(parts)


def render_html(files: list[SourceFile]) -> str:
    """Returns the content of `doc/file_map.html`: packages nest by directory, and every entry collapses."""
    by_path = {f.path: f for f in files}
    grouped = dict(sections(files))

    def parent_of(directory: str) -> str:
        """Returns the nearest listed directory that contains this one, '' for the project root."""
        containing = [other for other in grouped if other and directory.startswith(other + '/')]
        return max(containing, key=len) if containing else ''

    def render_directory(directory: str) -> str:
        children = sorted(d for d in grouped if d and d != directory and parent_of(d) == directory)
        summary = inline_html(directory_summary(directory, by_path) or '')
        parent = parent_of(directory)
        name = directory[len(parent) + 1:] if parent else directory
        label = html.escape(f'{name}/' if directory else 'IntraPaint/')
        open_attribute = ' open' if directory == '' else ''
        lines = [f'<details class="package"{open_attribute}><summary><code>{label}</code> '
                 f'{summary}</summary>']
        for child in children:
            lines.append(render_directory(child))
        lines.extend(render_file_html(f) for f in grouped.get(directory, []) if not f.path.endswith('/__init__.py'))
        lines.append('</details>')
        return '\n'.join(lines)

    return ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            f'<title>IntraPaint file map</title><style>{HTML_STYLE}</style></head><body>'
            '<h1>IntraPaint file map</h1><p class="intro">Generated by <code>python scripts/file_map.py</code> from '
            'module docstrings. Expand a file for its docstring, size, classes and importers.</p>'
            '<input id="filter" type="search" placeholder="Filter by path or description">\n'
            f'{render_directory(PROJECT_ROOT)}\n<script>{HTML_SCRIPT}</script></body></html>\n')


def main() -> int:
    """Writes or checks the file map."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='exit 1 if any summary has a problem or doc/file_map.md is out of date')
    args = parser.parse_args()

    files = collect(tracked_files())
    problems = [f for f in files if f.problem]
    for source_file in problems:
        print(f'{source_file.path}: {source_file.problem}')
    markdown = render_markdown(files)
    map_file = os.path.join(PROJECT_DIR, MAP_PATH)

    if args.check:
        with open(map_file, encoding='utf-8') as file:
            stale = file.read() != markdown
        if stale:
            print(f'{MAP_PATH} is out of date: run python scripts/file_map.py')
        return 1 if problems or stale else 0

    with open(map_file, 'w', encoding='utf-8') as file:
        file.write(markdown)
    with open(os.path.join(PROJECT_DIR, HTML_PATH), 'w', encoding='utf-8') as file:
        file.write(render_html(files))
    print(f'Wrote {MAP_PATH} and {HTML_PATH}: {len(files)} files, {len(problems)} summary problems.')
    return 0


if __name__ == '__main__':
    sys.exit(main())

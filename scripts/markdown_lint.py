"""CI markdown gate: lint the repository's Markdown files with PyMarkdown, using the rules in .pymarkdown.yaml.

Every tracked .md file is checked except the ones in EXCLUDED. Line length (MD013) is checked everywhere except
LONG_LINE_DOCS, the user-facing guides written with one paragraph or list item per line. A guide leaves that list
when its lines are wrapped to the configured length.

Usage: python scripts/markdown_lint.py [--fix]
  --fix applies the fixes PyMarkdown can make itself and then reports what is left.
"""
import argparse
import os
import subprocess
import sys

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Generated by release-please, or vendored from the legacy GLID-3-XL code.
EXCLUDED = {'doc/CHANGELOG.md', 'src/glid_3_xl/GLID-3-XL-DOC.md'}

LONG_LINE_DOCS = {
    'README.md',
    'doc/controls.md',
    'doc/inpainting_guide.md',
    'doc/menu_options.md',
    'doc/stable-diffusion.md',
    'doc/stable_diffusion_setup.md',
    'doc/tool_guide.md',
}


def tracked_markdown() -> list[str]:
    """Returns the repo-relative paths of tracked Markdown files that should be linted."""
    listing = subprocess.run(['git', 'ls-files', '*.md'], cwd=PROJECT_DIR, capture_output=True, text=True, check=True)
    return sorted(path for path in listing.stdout.splitlines() if path not in EXCLUDED)


def run_pymarkdown(command: str, paths: list[str], disabled_rules: str | None = None) -> int:
    """Runs one `pymarkdown` command over paths and returns its exit status."""
    if not paths:
        return 0
    args = [sys.executable, '-m', 'pymarkdown']
    if disabled_rules:
        args += ['--disable-rules', disabled_rules]
    return subprocess.run(args + [command, *paths], cwd=PROJECT_DIR, check=False).returncode


def main() -> None:
    """Lints (or fixes) the tracked Markdown files and exits non-zero if any rule fails."""
    parser = argparse.ArgumentParser(description=__doc__.split('\n', maxsplit=1)[0])
    parser.add_argument('--fix', action='store_true', help='apply the fixes PyMarkdown can make, then lint')
    args = parser.parse_args()

    paths = tracked_markdown()
    long_line_paths = [path for path in paths if path in LONG_LINE_DOCS]
    strict_paths = [path for path in paths if path not in LONG_LINE_DOCS]
    if args.fix:
        run_pymarkdown('fix', strict_paths)
        run_pymarkdown('fix', long_line_paths, disabled_rules='md013')
    failed = run_pymarkdown('scan', strict_paths) | run_pymarkdown('scan', long_line_paths, disabled_rules='md013')
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
